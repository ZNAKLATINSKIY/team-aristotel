# 2. Запросите два целых числа a и b. Если a больше b, вычислите и
# выведите их среднее арифметическое:
def ex_two():
    a = int(input("Введите число А: "))
    b = int(input("Введите число B: "))
    if(a > b):
        print(f"Среднее арифметическое чисел: {a*b/2}")
    else:
        print(f"Среднее геометрическое чисел: Корень из {a*b}")

