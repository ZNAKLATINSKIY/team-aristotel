# Напишите программу, которая:
# Использует модуль random для генерации случайного числа в
# диапазоне от 1 до 100.
# Проверяет, является ли сгенерированное число чётным или
# нечётным.
# Выводит сгенерированное число и сообщение: "Число чётное" или
# "Число нечётное".

def ex_three():
    num = int(random.randint(1, 1000))
    result = "Число чётное" if (num % 2 == 0) else "Число нечётное"
    print(result)

